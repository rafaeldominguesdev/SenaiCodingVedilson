package prjSenaiMusic.Classes;

public class EpisodioPodcast {
	
	//Atributos 
	private String nomeDoPrograma;
	private String nomeDoConvidado;
	
	
	//Getters & Setters 
	
	public String getNomeDoConvidado() {
		return nomeDoConvidado;
	}
	public void setNomeDoConvidado(String nomeDoConvidado) {
		this.nomeDoConvidado = nomeDoConvidado;
	}
	public String getNomeDoPrograma() {
		return nomeDoPrograma;
	}
	public void setNomeDoPrograma(String nomeDoPrograma) {
		this.nomeDoPrograma = nomeDoPrograma;
	}
}
