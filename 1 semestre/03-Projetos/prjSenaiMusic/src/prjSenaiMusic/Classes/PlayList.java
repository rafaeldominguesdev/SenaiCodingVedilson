package prjSenaiMusic.Classes;

public class PlayList {
	
	//Atributos 
	
	private String tituloDaPlayList;
	private String dataDeCriacao;
	private String conteudo;
	
	
	
	//Getters & Setters 
	
	public String getTituloDaPlayList() {
		return tituloDaPlayList;
	}
	public void setTituloDaPlayList(String tituloDaPlayList) {
		this.tituloDaPlayList = tituloDaPlayList;
	}
	public String getDataDeCriacao() {
		return dataDeCriacao;
	}
	public void setDataDeCriacao(String dataDeCriacao) {
		this.dataDeCriacao = dataDeCriacao;
	}
	public String getConteudo() {
		return conteudo;
	}
	public void setConteudo(String conteudo) {
		this.conteudo = conteudo;
	}
}
